#pragma once

#include <initguid.h>

DEFINE_GUID(GUID_DEVINTERFACE_REMOTEMIC_HID_FILTER,
    0xa88b865d, 0xd5ab, 0x4232, 0xa0, 0x2d, 0x5d, 0xe8, 0x77, 0x35, 0x42, 0x0f);

#define IOCTL_REMOTEMIC_GET_LATEST_REPORT \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_READ_DATA)
#define IOCTL_REMOTEMIC_GET_DIAGNOSTICS \
    CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_READ_DATA)

#define REMOTEMIC_MAX_REPORT_BYTES 64

typedef struct _REMOTEMIC_FILTER_REPORT {
    ULONG Sequence;
    ULONG Length;
    UCHAR Data[REMOTEMIC_MAX_REPORT_BYTES];
} REMOTEMIC_FILTER_REPORT, *PREMOTEMIC_FILTER_REPORT;

typedef struct _REMOTEMIC_FILTER_DIAGNOSTICS {
    ULONG Version;
    ULONG DeviceAdds;
    ULONG Reads;
    ULONG DeviceControls;
    ULONG InternalControls;
    ULONG Completions;
    ULONG LastRequestType;
    ULONG LastDeviceIndex;
    ULONG LastIoctl;
    ULONG LastStatus;
    ULONG LastInformation;
    ULONG LastRetrieveStatus;
    ULONG LastBufferLength;
    UCHAR LastData[REMOTEMIC_MAX_REPORT_BYTES];
} REMOTEMIC_FILTER_DIAGNOSTICS, *PREMOTEMIC_FILTER_DIAGNOSTICS;
